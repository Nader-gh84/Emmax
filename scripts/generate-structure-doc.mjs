import fs from "fs";
import path from "path";

const root = process.cwd();
const excludeDirs = new Set(["node_modules", ".next", ".git", "scripts"]);
const excludeFiles = new Set([
  "package-lock.json",
  "PROJECT_STRUCTURE.md",
  ".env.local",
]);
const extOk = new Set([".ts", ".tsx", ".css", ".json", ".mjs", ".md", ".example"]);

function walk(dir, files = []) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    if (
      entry.name.startsWith(".") &&
      entry.name !== ".env.local.example" &&
      entry.name !== ".eslintrc.json" &&
      entry.name !== ".gitignore"
    ) {
      continue;
    }
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      if (excludeDirs.has(entry.name)) continue;
      walk(full, files);
    } else {
      const rel = path.relative(root, full).replace(/\\/g, "/");
      if (excludeFiles.has(entry.name) || excludeFiles.has(rel)) continue;
      const ext = path.extname(entry.name);
      if (
        !extOk.has(ext) &&
        entry.name !== ".gitignore" &&
        entry.name !== ".eslintrc.json"
      ) {
        continue;
      }
      files.push(rel);
    }
  }
  return files.sort();
}

function langFor(file) {
  if (file.endsWith(".tsx")) return "tsx";
  if (file.endsWith(".ts")) return "typescript";
  if (file.endsWith(".css")) return "css";
  if (file.endsWith(".json")) return "json";
  if (file.endsWith(".mjs")) return "javascript";
  return "text";
}

const files = walk(root);
